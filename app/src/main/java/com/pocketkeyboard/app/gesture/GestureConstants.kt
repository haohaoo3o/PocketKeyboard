package com.pocketkeyboard.app.gesture

import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp

/**
 * 五指手势引擎的全部判定阈值（集中在此，便于真机调试）。
 *
 * 五指手势**只有短按一种**（5 指凑齐后快速原地抬起 → 返回键盘页面）；
 * 收缩 / 张开 / 横滑那套几何判定已按产品决策移除（真机太难触发、互相误判）。
 *
 * 调参指引：
 * - 觉得短按太难触发 → 调大 [FIVE_FINGER_TAP_MAX_MS] / [FIVE_FINGER_TAP_SLOP]；
 * - 觉得歇手（5 指放着不动）也误触发 → 调小 [FIVE_FINGER_TAP_MAX_MS]；
 * - 真机上五指经常凑不齐 → 调大 [FINGER_GATHER_RENEW_MS] / [FINGER_GATHER_MAX_MS]。
 *   注意凑指窗口同时决定触控板层要等多久：窗口内已按下的手指一旦明显在动
 *   （超过 [FINGER_GATHER_MOVE_SLOP]）且没有新手指继续落下，五指层会**立刻**放手，
 *   因此调大这两个值不会给单指触控板操作带来延迟，只会让五指手势更容易凑齐。
 */
object GestureConstants {

    /** 触发五指手势所需的同时按下指针数。 */
    const val REQUIRED_FINGER_COUNT: Int = 5

    /**
     * 五指短按的最长时长：从第 5 指落下（凑齐）到最后全部抬起之间超过它就不算短按。
     *
     * 取 600ms：真人「五指点一下」从凑齐到离屏通常 100–400ms；而「5 指歇在屏上」
     * 至少是秒级。窗口从**凑齐**起算而不是第一指落下，摆指慢的人（凑指花 500ms+）
     * 也能打出短按。
     */
    const val FIVE_FINGER_TAP_MAX_MS: Long = 600L

    /**
     * 五指短按的**单指**位移容差：跟踪期间任何一根手指相对自己落点的漂移超过它
     * 就不算短按（那是拖动 / 滑动，不是轻点）。取 24dp，与 [FINGER_GATHER_MOVE_SLOP] 同量级。
     * 刻意按单指而非质心判定：逐个抬指时质心跳变很大，按质心判会把正常抬手错杀成拖动。
     */
    val FIVE_FINGER_TAP_SLOP: Dp = 24.dp

    /**
     * 「有五指挥势意图」的手指数阈值。
     *
     * 凑指窗口内观察到这么多手指，就认为用户正在摆五指手势：此刻要
     * ① 主动收起系统输入法（竖屏融合页唤起键盘后，屏幕下半被 IME 窗口占着，
     *    落在 IME 上的手指到不了 App 手势层，5 指永远凑不齐——这是上一轮
     *    五指挥势「不灵」的主因，见 FusedControlScreen 的 IME 联动）；
     * ② 让按键层停止激活（见 [KEY_PRESS_FIVE_FINGER_GUARD_MS]）。
     *
     * 取 3 而不是 2：双指是触控板上的常规手势（滚动 / 缩放），不能碰一下就收键盘；
     * 三指在触控板页也仍归触控板层（挥手），只是顺手把输入法让开。
     */
    const val FIVE_FINGER_INTENT_FINGER_COUNT: Int = 3

    /**
     * 按键激活的**五指防误触门控**时长。
     *
     * 键帽（87 键 / 小键盘 / 修饰键排）在手指落下时还不能知道这次触摸会不会长成
     * 五指挥势——第 5 根手指还没落下。若照旧在 `down` 就激活，用户做一次捏合
     * 就会先把落在键帽上的那几颗键打给被控设备（用户反馈的误触）。因此按下后
     * 先按住不激活，最多等这么久：
     *
     * - 等待期间**按下指针数达到 5** → 判定为五指挥势，本次按下整体作废，
     *   **一次 HID 报告都不发**（防误触的硬保证）；
     * - 等待期间有**别的指针抬起**（按下总数下降）→ 不可能是五指伸展，立刻激活
     *   （保证「按住 ctrl 再点 c」这类和弦的时序：修饰键先生效）；
     * - 超时 → 正常激活（单指打字不会感觉到，见下）。
     *
     * 取 300ms 与凑指窗口的续期步长 [FINGER_GATHER_RENEW_MS] 对齐：五指手势的
     * 5 根手指通常在一两次续期内落齐，因此绝大多数五指手势都能在激活前被认出来。
     * 单指**轻点**不受影响——孤指点起的那一刻按下总数已归 0，立即激活并松开，
     * 与改动前的观感一致；被延后的只有「按住不放」的键（长按修饰键和弦），
     * 延迟上限即本常量。
     */
    const val KEY_PRESS_FIVE_FINGER_GUARD_MS: Long = 300L

    /**
     * 轻点在「还有别人按着」时的收敛时长。
     *
     * 一颗键抬起时若屏幕上还有别的指针按着（典型：按住 ctrl 再点 c），它要等
     * 那颗**先按下的修饰键**激活之后再激活，否则字符会插到修饰键前面、和弦失效。
     * 这里给一个很短的收敛窗口；超过它还没等到修饰键激活（修饰键被 5 指作废、
     * 或压根没有修饰键）就照常激活，不让 Chord 无限等。
     */
    const val KEY_TAP_SETTLE_MS: Long = 120L

    /**
     * 触控板底部点击区（鼠标左 / 右键）的激活门控时长。
     *
     * 与 [KEY_PRESS_FIVE_FINGER_GUARD_MS] 同一套机制，但取短得多的值：点击区是
     * 「按住拖动」的高频目标（按住左半区划选文字），按下晚 300ms 会明显拖累拖拽；
     * 而它是鼠标键不是字符键，偶尔被五指手势带出一个多余点击的代价也低得多。
     * 孤立轻点仍然零延迟（点起即激活并松开），被延后的只有「按住不放」的拖拽。
     */
    const val CLICK_ZONE_PRESS_GUARD_MS: Long = 100L

    /**
     * dock（底部模式切换栏）激活后的**自动隐藏**时长。
     *
     * 边缘内滑唤出 dock 后，用户可能只是看一眼就继续操作键盘 / 触控板——dock
     * 常显会一直占着底部空间、也会挡住五指挥势。因此激活后无操作这么久就自动收起；
     * 期间每次与 dock 交互（点击导航项 / 触摸 dock 本身）都把倒计时续期。
     */
    const val DOCK_AUTO_HIDE_MS: Long = 5_000L

    /**
     * 凑指窗口的**续期**步长：每有新手指落下，就把截止时间推到「该手指落下时刻 + 本时长」。
     *
     * 为什么不能用一个固定的总窗口：人手放下 5 根手指总有先后（熟练 80ms、认真摆位 200ms+），
     * 固定 60ms 意味着**人类几乎不可能凑齐**，五指挥势层永远等不到第 5 根手指。
     * 改成「每来一根就续期」后，慢速摆指也能凑齐，而已经按下的手指只要明显在动
     * （见 [FINGER_GATHER_MOVE_SLOP]）又会立刻放手，触控板手势不会被拖慢。
     */
    const val FINGER_GATHER_RENEW_MS: Long = 300L

    /**
     * 凑指窗口的**总上限**：第一根手指落下后，最多等这么久就必须给出裁决。
     *
     * 防止「每隔 250ms 补一根手指」把等待无限续期；超过上限仍不足 5 指即放手。
     */
    const val FINGER_GATHER_MAX_MS: Long = 800L

    /**
     * 仲裁的**安全超时**：触控板层等待五指层裁决的最长等待时间。
     *
     * 正常流程里五指层一定会在 [FINGER_GATHER_MAX_MS] 内给出裁决（claimFiveFinger 或
     * releaseToTrackpad），这个值只是兜底——万一 `Modifier.pocketGestures` 没挂载
     * （调试时 enabled = false），触控板层等这么久后也会自己接管，不会永久卡死。
     * 它**不是**仲裁窗口本身：仲裁是事件驱动的，五指层一放手触控板层立刻接管。
     */
    const val ARBITRATION_SAFETY_TIMEOUT_MS: Long = 1_500L

    /**
     * 凑指期的「明显在动」阈值：已按下的手指相对基准位置位移超过它、且没有新手指继续落下，
     * 就判定「这是一次正在进行的触控板手势」，五指层立刻释放给触控板层。
     *
     * 取 24dp（与 dock 边缘内滑的触发距离同量级）：远大于摆指时的指尖抖动，
     * 又小到「按下即拖动」的触控板操作几乎察觉不到延迟。基准位置每来一根新手指就重设一次，
     * 所以「慢慢把 5 根手指摆开」不会被误判成拖动。
     *
     * **只对 1–2 指生效**（真机实测第三轮修正）：张开 / 捏合手势的手指是「边落边扩」的，
     * 位移分分钟超过本阈值——若 3 指以上也据此放手，用户看到的症状就是「五指短按
     * 没反应」（手指一分开五指层就交还给了触控板层）。≥
     * [FIVE_FINGER_INTENT_FINGER_COUNT] 指（意图已确立）后不再因位移放手，
     * 只受 [FINGER_GATHER_MAX_MS] 总窗口上限约束。
     */
    val FINGER_GATHER_MOVE_SLOP: Dp = 24.dp

    /** HUD 文字提示可见时长，到期后开始淡出。 */
    const val HUD_VISIBLE_MS: Long = 1_000L

    /** HUD 淡出动画时长。 */
    const val HUD_FADE_MS: Int = 220

}
